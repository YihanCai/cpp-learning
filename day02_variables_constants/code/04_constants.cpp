// 04.变量和常量 —— 常量
// Day 02 / 课程 04
//
// 知识点：
//   1. C++ 里定义常量有两种方式：#define 宏常量 和 const 修饰的变量
//   2. 常量一旦定义，程序运行期间不能修改（改了直接编译报错）
//   3. #define 是"文本替换"，const 是"只读变量"——本质完全不同
//   4. 实战意义：消灭"魔法数字"，让代码自解释

#include <iostream>
using namespace std;

// ============================================================
// 方式一：#define 宏常量（写在文件开头，函数外面）
// 语法：#define 常量名 常量值
// 习惯：常量名全大写，用下划线分词
// 注意：结尾不写分号！它只是文本替换，不是语句
// ============================================================
#define PI 3.1415926
#define MAX_SCORE 100

int main() {
    // ========================================================
    // 方式二：const 修饰的变量（写在函数里或外都行）
    // 语法：const 数据类型 常量名 = 常量值;
    // ========================================================
    const double PI2 = 3.1415926;
    const int DAYS_IN_WEEK = 7;

    // ---------- 字面常量：直接写在代码里的值 ----------
    // 前面那些 3.1415926、100 叫"字面常量"（literal）
    // 问题是：它没有名字，读代码的人不知道它是什么意思
    cout << "---- 三种常量都能用 ----" << endl;
    cout << "#define  PI          = " << PI << endl;
    cout << "const    PI2         = " << PI2 << endl;
    cout << "字面常量 3.1415926   = " << 3.1415926 << endl;
    cout << "MAX_SCORE            = " << MAX_SCORE << endl;
    cout << "DAYS_IN_WEEK         = " << DAYS_IN_WEEK << endl;

    // ---------- 常量拿来算东西 ----------
    double radius = 2.0;
    cout << "\n---- 用常量算圆面积 ----" << endl;
    cout << "半径 " << radius << " 的圆面积 = " << PI * radius * radius << endl;

    // ---------- 常量的价值：消灭魔法数字 ----------
    // ❌ 反例：下面这些数字过一个月自己都忘了是什么
    // double area1 = 3.1415926 * 2.0 * 2.0;
    //
    // ✅ 正例：名字即文档
    double area = PI * radius * radius;
    cout << "面积 = " << area << "（写法自带说明：PI 是什么一眼就懂）" << endl;

    // ---------- 常量不能被修改 ----------
    // 下面两行取消注释都会编译报错，这就是"常量"的意义所在：
    //
    // PI2 = 3.14;              // ❌ error C3892: 不能给常量赋值
    // #define 的值更不能改，它是文本替换
    //
    cout << "\n---- 常量不可修改 ----" << endl;
    cout << "试着取消注释代码里那两行赋值，编译会直接报错 C3892。" << endl;

    // ---------- 常量的常见用法：数组长度 / 循环上界 ----------
    const int SIZE = 5;
    int scores[SIZE] = {90, 85, 77, 92, 88};   // 用常量当数组长度，想改只改一处

    cout << "\n---- 常量当数组长度 ----" << endl;
    int sum = 0;
    for (int i = 0; i < SIZE; i++) {            // 上界也用同一个常量
        cout << "scores[" << i << "] = " << scores[i] << endl;
        sum += scores[i];
    }
    cout << "总分 " << sum << "，平均 " << (double)sum / SIZE << endl;
    cout << "（想改成 10 个元素？只改 SIZE 一处即可，不用到处找数字）" << endl;

    return 0;
}
