// 04.变量和常量 —— 陷阱与 #define / const 的真实区别
// Day 02 / 课程 04 补充
//
// 这一节是视频之外自己踩出来的，三个坑：
//   1. 局部变量不初始化 = 垃圾值（编译器只警告，不报错）
//   2. #define 是纯文本替换，会踩运算符优先级的坑
//   3. #define 不遵守作用域，也没有类型

#include <iostream>
using namespace std;

// ---------- 陷阱①：文本替换不看优先级 ----------
#define BAD_VALUE 1 + 2
const int GOOD_VALUE = 1 + 2;

// ---------- 陷阱②：#define 没有类型 ----------
#define HUNDRED 100

int main() {
    // ============================================================
    // 坑 1：局部变量不初始化，值是不确定的
    // ============================================================
    cout << "---- 坑 1：未初始化的局部变量 ----" << endl;

    int uninit;              // 只声明，没给初值
    cout << "uninit = " << uninit << "（每次运行可能都不一样！）" << endl;
    cout << "↑ 编译器会给 warning C4700，但不会报错，照样编过。" << endl;
    cout << "  这不是'值等于 0'，而是'这块内存里残留着什么就是什么'。" << endl;

    if (uninit > 0) {        // 拿垃圾值做判断，行为完全不可预测
        cout << "  刚才那个垃圾值恰好 > 0，于是走进了这个分支" << endl;
    } else {
        cout << "  刚才那个垃圾值 <= 0" << endl;
    }

    // ✅ 正确做法：定义时就给初值，或者用列表初始化
    int safe{};              // 明确初始化成 0
    cout << "safe   = " << safe << "（用 {} 初始化，明确为 0）" << endl;

    // ============================================================
    // 坑 2：#define 是纯文本替换
    // ============================================================
    cout << "\n---- 坑 2：宏的文本替换陷阱 ----" << endl;

    // 你写的是 BAD_VALUE * 3，心里想着 (1+2)*3 = 9
    // 但预处理后实际变成  1 + 2 * 3，先算乘法 → 7
    cout << "BAD_VALUE  * 3 = " << BAD_VALUE * 3 << "  ← 期望 9，实际 7！" << endl;
    cout << "GOOD_VALUE * 3 = " << GOOD_VALUE * 3 << "  ← const 是 9，符合预期" << endl;
    cout << "原因：#define 只是把 '1 + 2' 这串文字原样贴进去，没有括号。" << endl;

    // 想用宏就得自己加括号，非常反直觉：
    #define OK_VALUE (1 + 2)
    cout << "括号包一下 OK_VALUE * 3 = " << OK_VALUE * 3 << "  ← 这才对" << endl;
    // 但既然要到处加括号防坑，为什么不直接用 const 呢？

    // ============================================================
    // 坑 3：#define 不遵守作用域，也没有类型
    // ============================================================
    cout << "\n---- 坑 3：宏没有类型、不认作用域 ----" << endl;

    {
        #define INNER 999
    }
    // 出了花括号，INNER 居然还活着 —— 因为 #define 从定义处一直有效到文件结尾
    cout << "花括号外面的 INNER = " << INNER << "  ← 本该出了作用域，但它还在" << endl;

    {
        const int inner = 888;
        cout << "花括号里的 const inner = " << inner << endl;
    }
    // cout << inner;   // ← 取消注释会报错：inner 未声明。const 严格遵守作用域 ✅

    cout << "\n---- #define 和 const 对比小结 ----" << endl;
    cout << "sizeof(HUNDRED) = " << sizeof(HUNDRED) << "  ← 宏本身没有类型，按字面量 int 算" << endl;

    return 0;
}
