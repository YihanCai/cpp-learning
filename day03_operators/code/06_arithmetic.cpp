// 06.运算符 —— 算术运算符
// Day 03 / 课程 06
//
// 知识点：
//   1. 五个算术运算符：+ - * / %  和自增自减 ++ --
//   2. 【重点】整数除法会截断小数，不是四舍五入
//   3. 【重点】取模 % 只能用于整数，负数取模的符号规则
//   4. 【重点】前置 ++i 和后置 i++ 的区别
//   5. 除数不能为 0

#include <iostream>
#include <cmath>      // fmod() 浮点取余
using namespace std;

int main() {
    // ============================================================
    // 1. 基本算术
    // ============================================================
    int a = 10, b = 3;

    cout << "---- 五个基本运算符 ----" << endl;
    cout << "a + b = " << a + b << endl;   // 13
    cout << "a - b = " << a - b << endl;   // 7
    cout << "a * b = " << a * b << endl;   // 30
    cout << "a / b = " << a / b << endl;   // 3  ← 不是 3.33！
    cout << "a % b = " << a % b << endl;   // 1  ← 余数

    // ============================================================
    // 2. 【重点】整数除法会截断
    // ============================================================
    cout << "\n---- 整数除法陷阱 ----" << endl;
    cout << "10 / 3     = " << 10 / 3 << "        ← 两个整数相除，结果也是整数" << endl;
    cout << "10.0 / 3   = " << 10.0 / 3 << "  ← 有小数参与，才是真正的除法" << endl;
    cout << "10 / 3.0   = " << 10 / 3.0 << "  ← 只要一边是小数就行" << endl;
    cout << "10 / 3.0f  = " << 10 / 3.0f << "  ← 默认 cout 只显示 6 位有效数字" << endl;

    // 想要精确的除法，必须把其中一个操作数转成浮点
    int x = 10, y = 3;
    cout << "\n(int)x / y          = " << x / y << "   ← 还是整数除法" << endl;
    cout << "(double)x / y       = " << (double)x / y << "  ← 转一个就行" << endl;
    cout << "x / (double)y       = " << x / (double)y << "  ← 转哪个都一样" << endl;

    // ============================================================
    // 3. 【重点】取模运算符 %
    // ============================================================
    cout << "\n---- 取模 % ----" << endl;
    cout << "10 % 3  = " << 10 % 3 << endl;    // 1
    cout << "10 % 5  = " << 10 % 5 << endl;    // 0  ← 能整除就是 0
    cout << "3 % 10  = " << 3 % 10 << endl;    // 3  ← 小的模大的，还是自己

    // 负数取模：C++11 起，结果的符号跟【被除数】走，不是跟除数
    cout << "\n负数取模（结果的符号跟被除数）：" << endl;
    cout << " 7 %  3 = " << (7 % 3) << endl;    // 1
    cout << "-7 %  3 = " << (-7 % 3) << endl;   // -1  ← 注意是负数！
    cout << " 7 % -3 = " << (7 % -3) << endl;   // 1
    cout << "-7 % -3 = " << (-7 % -3) << endl;  // -1
    cout << "（不同语言规则不同，写跨语言代码时要小心）" << endl;

    // % 只能用于整数
    // cout << 10.0 % 3;   // ❌ 编译报错：% 的操作数必须是整数
    cout << "\n浮点数取余要用 fmod()：" << endl;
    cout << "fmod(10.5, 3.0) = " << fmod(10.5, 3.0) << "（需要 #include <cmath>）" << endl;

    // ============================================================
    // 4. 【重点】前置 ++ 和后置 ++
    // ============================================================
    cout << "\n---- ++i 和 i++ ----" << endl;

    int i = 5;
    int r1 = i++;   // 后置：先把自己的值交出去，再自增
    cout << "i=5 时  r1 = i++  →  r1 = " << r1 << "，i = " << i << endl;

    int j = 5;
    int r2 = ++j;   // 前置：先自增，再把新值交出去
    cout << "j=5 时  r2 = ++j  →  r2 = " << r2 << "，j = " << j << endl;

    cout << "\n记忆方法：" << endl;
    cout << "  i++  的 + 在后面 → 先取值，后加" << endl;
    cout << "  ++i  的 + 在前面 → 先加，后取值" << endl;
    cout << "  【单独一行时 i++; 和 ++i; 完全等价】，区别只在被赋值/被使用时" << endl;

    // 单独使用时确实没区别
    int m = 5, n = 5;
    m++;
    ++n;
    cout << "\n单独一行：m++ 后 m = " << m << "，++n 后 n = " << n << "（一样）" << endl;

    // 后置自增的经典用法
    cout << "\n经典用法（先输出再自增）：" << endl;
    int k = 0;
    cout << "k++ 输出：";
    for (int t = 0; t < 3; t++) {
        cout << k++ << " ";     // 输出 0 1 2
    }
    cout << "→ 循环结束后 k = " << k << endl;

    int p = 0;
    cout << "++p 输出：";
    for (int t = 0; t < 3; t++) {
        cout << ++p << " ";     // 输出 1 2 3
    }
    cout << "→ 循环结束后 p = " << p << endl;

    // ============================================================
    // 5. 单独使用的一元运算符
    // ============================================================
    cout << "\n---- 一元 + 和 - ----" << endl;
    int v = 7;
    cout << "+v = " << +v << "，-v = " << -v << endl;
    cout << "（一元 + 几乎没用处，知道有这个写法就行）" << endl;

    // ============================================================
    // 6. 除数不能为 0
    // ============================================================
    cout << "\n---- 除数不能为 0 ----" << endl;
    cout << "整数除以 0 是【未定义行为】，程序通常会直接崩溃（不是返回 0，也不是报个错继续跑）。" << endl;
    cout << "浮点除以 0 则不同，会得到 inf（无穷大），程序不崩。" << endl;
    cout << "见 06_pitfalls.cpp 里的实测。" << endl;

    return 0;
}
