// 06.运算符 —— 赋值运算符 与 比较运算符
// Day 03 / 课程 06
//
// 知识点：
//   1. 赋值 = 和复合赋值 += -= *= /= %=
//   2. 比较运算符 == != > < >= <=，结果是 bool
//   3. 【重点】= 和 == 的区别（C++ 里最容易犯的错）
//   4. 浮点数不能直接用 == 比较

#include <iostream>
#include <cmath>      // fabs()
using namespace std;

int main() {
    // ============================================================
    // 1. 赋值运算符
    // ============================================================
    cout << "---- 复合赋值 ----" << endl;

    int a = 10;
    cout << "初始 a = " << a << endl;

    a += 5;   cout << "a += 5  后 a = " << a << "   （等价 a = a + 5）" << endl;
    a -= 3;   cout << "a -= 3  后 a = " << a << "   （等价 a = a - 3）" << endl;
    a *= 2;   cout << "a *= 2  后 a = " << a << "  （等价 a = a * 2）" << endl;
    a /= 4;   cout << "a /= 4  后 a = " << a << "    （等价 a = a / 4，注意是整数除法）" << endl;
    a %= 3;   cout << "a %= 3  后 a = " << a << "    （等价 a = a % 3）" << endl;

    cout << "\n复合赋值的好处：写起来短，而且左边只求值一次（有副作用时更安全）。" << endl;

    // 无符号的坑：a -= 1 从 0 变成最大值
    cout << "\n---- 无符号变量的 -= 陷阱 ----" << endl;
    unsigned int u = 0;
    cout << "unsigned int u = 0;" << endl;
    cout << "u -= 1 之后 u = " << u - 1 << "  ← 不是 -1，而是回绕到最大值" << endl;

    // ============================================================
    // 2. 比较运算符
    // ============================================================
    cout << "\n---- 比较运算符 ----" << endl;

    int x = 5, y = 8;

    cout << "x = " << x << ", y = " << y << endl;
    cout << "x == y : " << (x == y) << "   （相等？）" << endl;
    cout << "x != y : " << (x != y) << "   （不等？）" << endl;
    cout << "x >  y : " << (x > y) << "   （大于？）" << endl;
    cout << "x <  y : " << (x < y) << "   （小于？）" << endl;
    cout << "x >= y : " << (x >= y) << "   （大于等于？）" << endl;
    cout << "x <= y : " << (x <= y) << "   （小于等于？）" << endl;

    cout << "\n注意：比较的结果是 bool，默认打印成 1 / 0。" << endl;
    cout << "想看 true / false，加 boolalpha：" << boolalpha << endl;
    cout << "  x == y : " << (x == y) << endl;
    cout << "  x != y : " << (x != y) << endl;
    cout << "  10 > 3 : " << (10 > 3) << endl;
    cout << noboolalpha << "（用 noboolalpha 恢复成 1 / 0）" << endl;

    // ============================================================
    // 3. 【重点】= 和 == 千万不能混
    // ============================================================
    cout << "\n---- = 和 == 的区别 ----" << endl;
    cout << "=  是【赋值】，把右边的值放进左边" << endl;
    cout << "== 是【比较】，判断两边是否相等" << endl;

    int flag = 0;

    // ❌ 反面教材：把 = 写成 ==，或者反过来
    // if (flag = 1) { }   // 这是【赋值】！flag 变成 1，条件永远为真
    //
    // 实测：下面这段会走进 if 分支，因为 flag 被赋成了 1（非 0 即真）
    if (flag = 1) {
        cout << "\nif (flag = 1) 走进了这个分支 —— 因为赋值成功，flag = " << flag << endl;
        cout << "写成 if (flag == 1) 才对，那样 flag 是 0，不会进来。" << endl;
    }

    // 防御写法：把常量写在左边，写错就编译报错
    // if (1 = flag) { }   // ❌ error C2106: 左操作数必须为左值 —— 编译期就拦住
    cout << "\n防御技巧：把常量写在左边（1 == flag），写漏一个 = 会直接编译报错。" << endl;

    // ============================================================
    // 4. 【重点】浮点数不能直接用 ==
    // ============================================================
    cout << "\n---- 浮点数的 == 陷阱 ----" << endl;

    double d1 = 0.1, d2 = 0.2;
    cout << "(0.1 + 0.2) == 0.3 ? " << ((d1 + d2) == 0.3) << "   ← 是 false！" << endl;

    const double EPS = 1e-9;
    cout << "正确写法：abs(差值) < EPS ? " << (fabs((d1 + d2) - 0.3) < EPS) << endl;
    cout << "（原因见 Day 01 笔记：0.1 和 0.2 在二进制里存不下精确值）" << endl;

    return 0;
}
